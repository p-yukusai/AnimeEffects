#!/usr/bin/env python3
"""Generate src/ctrl/ExportTargetStrings.h from assets/export/ExportTargets.txt.

WHY THIS EXISTS. The destination table is DATA (a deliberate choice: every fact in it
moves), and lupdate cannot read a data file. So the names and notes a user actually
reads were untranslatable: the table is full of platforms a non-English audience uses
(WeChat, KakaoTalk, Bilibili, pixiv, Nico Nico) and not one of their labels or notes
could be localized.

Qt's answer for a string the extractor cannot see is QT_TRANSLATE_NOOP: the string
appears in C++ with the context it will be translated in, and the parser calls
QCoreApplication::translate() with that same context at runtime. This script keeps the
two in step.

  usage: gen_export_targets_i18n.py [--check]

--check exits non-zero when the generated header is out of date, which is how a
destination added without regenerating fails loudly instead of shipping English into
five locales. The table test asserts the same thing from the other side (it compares
this header against the data file), because a check nobody runs is a promise.
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "assets" / "export" / "ExportTargets.txt"
OUT = ROOT / "src" / "ctrl" / "ExportTargetStrings.h"
CONTEXT = "ExportTargets"


def strings_from_data():
    """Every user-visible string in the table, in file order, de-duplicated."""
    tree = ET.parse(DATA)
    root = tree.getroot()
    out = []

    def add(text):
        text = (text or "").strip()
        if text and text not in out:
            out.append(text)

    groups = root.find("groups")
    if groups is not None:
        for g in groups.findall("group"):
            add(g.get("title"))
    for d in root.findall("destination"):
        add(d.get("label"))
        add(d.get("note"))
        note = d.find("note")
        if note is not None and note.text:
            # A note may be wrapped over several lines in the source; the parser
            # trims it, so the extracted form is the trimmed one.
            add(re.sub(r"\s+", " ", note.text))
    return out


def render(strings):
    body = "\n".join('        QT_TRANSLATE_NOOP("%s", %s),' % (CONTEXT, cpp_literal(s))
                     for s in strings)
    decoded = "\n".join('        QStringLiteral(%s),' % cpp_literal(s) for s in strings)
    return '''#ifndef CTRL_EXPORTTARGETSTRINGS_H
#define CTRL_EXPORTTARGETSTRINGS_H

// GENERATED by scripts/i18n/gen_export_targets_i18n.py from
// assets/export/ExportTargets.txt. DO NOT EDIT BY HAND; regenerate instead.
//
// The table is data and lupdate cannot read a data file, so every user-visible string
// in it is repeated here as a no-op for the extractor, in the SAME context the parser
// translates through ("%s"). tests/media_export_target.cpp asserts that this list and
// the data file agree, so adding a destination without regenerating fails loudly.
#include <QtGlobal>

#include <QStringList>

namespace ctrl {

// Never called for its result: it exists so the extractor sees these strings.
inline void exportTargetStrings() {
    const char* const strings[] = {
%s
    };
    (void)strings;
}

// The same list, decoded, for the test that keeps this file in step with the data
// table. Emitted from the same pass as the no-op list, so the two cannot disagree with
// each other; what they can disagree with is the TABLE, and that is what the test
// checks in both directions (a row added without regenerating, and an entry left over
// from a row that was deleted).
inline QStringList exportTargetStringList() {
    return QStringList{
%s
    };
}

} // namespace ctrl

#endif // CTRL_EXPORTTARGETSTRINGS_H
''' % (CONTEXT, body, decoded)


def cpp_literal(s):
    """A C++ string literal for arbitrary text (the table has CJK, Cyrillic, quotes)."""
    out = ['"']
    for ch in s:
        if ch in ('"', "\\"):
            out.append("\\" + ch)
        elif ch == "\n":
            out.append("\\n")
        elif ord(ch) < 32:
            out.append("\\x%02x" % ord(ch))
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main(argv):
    check = "--check" in argv
    strings = strings_from_data()
    wanted = render(strings)
    if check:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != wanted:
            print("%s is out of date: run scripts/i18n/gen_export_targets_i18n.py" % OUT)
            return 1
        print("%s is up to date (%d strings)" % (OUT, len(strings)))
        return 0
    OUT.write_text(wanted, encoding="utf-8")
    print("wrote %s (%d strings)" % (OUT, len(strings)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
